    /// Every CADCraft command is classified exactly once (offered, never, or not offered), and
    /// every listed one still exists. An upstream sync that adds a command fails here until it
    /// is reviewed.
    #[test]
    fn every_upstream_command_is_classified() {
        let ours: Vec<&str> = crate::commands::specs().iter().map(|c| c.id).collect();
        let specs = cadcraft_engine::command_specs();
        let offered: Vec<&str> = UPSTREAM_COMMANDS.iter().map(|(c, _)| *c).collect();
        let lists = [offered.as_slice(), NEVER_COMMANDS, NOT_OFFERED];
        for spec in specs.iter().filter(|s| !ours.contains(&s.id)) {
            let on = lists.iter().filter(|l| l.contains(&spec.id)).count();
            assert_eq!(
                on, 1,
                "`{}` is on {on} agent lists: offer it in agent/upstream.rs, refuse it in NEVER_COMMANDS, or list it as not offered",
                spec.id
            );
        }
        for id in offered.iter().chain(NOT_OFFERED) {
            assert!(specs.iter().any(|s| s.id == *id), "`{id}` is listed but no longer a CADCraft command");
        }
    }

    /// Upstream's own classification decides the file commands: every command it lists as touching
    /// files, or refuses under automation roots, is never run by an agent, and every offered one
    /// touches no file.
    #[test]
    fn upstream_file_commands_are_never_offered() {
        for id in FILES.iter().chain(REFUSED.iter().map(|(c, _)| c)) {
            assert!(NEVER_COMMANDS.contains(id), "`{id}` touches files upstream: add it to NEVER_COMMANDS");
        }
        for (id, _) in UPSTREAM_COMMANDS {
            assert!(NO_FILES.contains(id), "`{id}` is offered but upstream does not list it as touching no file");
            assert!(!NEVER_COMMANDS.contains(id), "`{id}` is both offered and never run");
        }
    }
