//! The CADCraft commands an agent may run on an ECAD project: a short, reviewed list of drawing
//! commands, each marked read or write ([`UPSTREAM_COMMANDS`]). Every other CADCraft command is
//! refused for agents ([`crate::agent::policy::check`]); the file and session commands among them are named in
//! [`crate::agent::policy::NEVER_COMMANDS`].
//!
//! # Semantics
//! - A command on this list runs exactly as for a person: ECAD's document owner records it as an
//!   edit of the page or refuses it in its own words.
//! - Each entry touches no file (it is on CADCraft's no-files list, `file_access::commands::NO_FILES`).
//! - An upstream sync that adds a command fails the classification test below until the command is
//!   reviewed: offered here, refused in `NEVER_COMMANDS`, or listed as not offered.

use crate::agent::policy::Offered;

/// The CADCraft commands offered to agents, with what each does to the project.
pub(crate) const UPSTREAM_COMMANDS: &[(&str, Offered)] = &[
    // Reading the active page; `query_entities` and `find_text` run `entities` and `texts`.
    ("entities", Offered::Read),
    ("texts", Offered::Read),
    ("shapes", Offered::Read),
    ("usage", Offered::Read),
    ("loops", Offered::Read),
    ("drawing.inspect", Offered::Read),
    ("getvar", Offered::Read),
    // Showing another open page of the project; records nothing.
    ("document.switch", Offered::Read),
    // Plain drawing, for a device drawn and then converted (`convertcomponent`).
    ("line", Offered::Write),
    ("pline", Offered::Write),
    ("circle", Offered::Write),
    ("arc", Offered::Write),
    ("rectang", Offered::Write),
    ("text", Offered::Write),
    ("mtext", Offered::Write),
    ("textedit", Offered::Write),
    // Editing what is on the page; ECAD moves what is attached or refuses what would break a meaning.
    ("move", Offered::Write),
    ("copy", Offered::Write),
    ("rotate", Offered::Write),
    ("mirror", Offered::Write),
    ("scale", Offered::Write),
    ("stretch", Offered::Write),
    ("erase", Offered::Write),
    ("oops", Offered::Write),
    ("explode", Offered::Write),
    ("join", Offered::Write),
    ("trim", Offered::Write),
    ("extend", Offered::Write),
    ("-array", Offered::Write),
    // Undo and redo, one step per call.
    ("u", Offered::Write),
    ("undo", Offered::Write),
    ("redo", Offered::Write),
    ("mredo", Offered::Write),
];

/// What CADCraft command `id` does for an agent, if it is offered.
pub(crate) fn offered(id: &str) -> Option<Offered> {
    UPSTREAM_COMMANDS.iter().find(|(c, _)| *c == id).map(|(_, o)| *o)
}

